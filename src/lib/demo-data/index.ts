// Cálculo dinâmico e estritamente derivado dos registros demonstrativos disponíveis (Seção 5.1)
export function getCalculatedHomeIndicators() {
  const publishedFutureProcurements = DEMO_PROCUREMENTS.filter(
    (p) => p.recordType === "PUBLISHED_BID"
  );
  const pcaPlannedProcurements = DEMO_PROCUREMENTS.filter(
    (p) => p.recordType === "PCA_PLANNING"
  );

  // Soma apenas valores efetivamente disponíveis (sem inventar valores para orçamentos sob sigilo legal)
  const totalEstimatedPublished = publishedFutureProcurements.reduce(
    (acc, item) => acc + (item.costs.estimatedValue ?? 0),
    0
  );
  const confidentialCount = publishedFutureProcurements.filter(
    (p) => p.costs.isBudgetConfidential
  ).length;

  const totalContractedInMonitoredWorks = DEMO_DELAYED_WORKS.reduce(
    (acc, w) => acc + w.costs.updatedAmountAfterAmendments,
    0
  );

  const totalContractsWithDocumentedOccurrences = DEMO_ATTENTION_CONTRACTS.length;

  return {
    futurePublishedBidsCount: publishedFutureProcurements.length,
    pcaPlannedCount: pcaPlannedProcurements.length,
    totalEstimatedFuturePublishedValue: totalEstimatedPublished,
    confidentialBudgetsExcludedCount: confidentialCount,
    identifiedParticipatingCompaniesCount: DEMO_COMPANIES.length,
    delayedWorksDocumentedCount: DEMO_DELAYED_WORKS.length,
    totalContractedInDelayedWorksValue: totalContractedInMonitoredWorks,
    contractsWithOccurrencesCount: totalContractsWithDocumentedOccurrences,
    lastCalculationTimestamp: "07/11/2026 às 08:00 (Base Demonstrativa Fase 1)",
  };
}
